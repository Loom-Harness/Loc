import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

// ---------------------------------------------------------------------------
// Repository-verb census (D-REPOSITORY-CONTRACT).
//
// The built-in repository verbs are declared once, in
// `src/util/repository-contract.ts`, and the IR carries each call's canonical
// `op`.  Every other module asks the contract (`repoVerbOp`, `repoVerbOpAt`,
// `repositoryVerb`, `isRepoWriteName`, `repoOpVerb`) or dispatches on the IR's
// `op` — it never compares a surface spelling.  A hand-written comparison
// against a verb name is how the old copies drifted: a verb typed `T` in one
// table and `T?` in another, a built-in read accepted in one position and
// unknown in the next.
//
// THE DETECTOR.  A source line (comments stripped) that uses one of the
// unambiguous built-in verb spellings as a dispatch key:
//
//   1. a comparison `<…method|member|verb> ===/!== "<verb>"`;
//   2. a `new Set([…])` literal naming the verb.
//
// The spellings are the three that mean nothing but a repository verb —
// `getById`, `findById`, `findAll`.  The short verbs (`find`, `all`, `run`,
// `delete`, `remove`) are also collection ops, statement kinds, API-op kinds
// and target method names, so a textual census cannot tell them apart; the
// typed IR `op` covers them instead.
//
// EXEMPT: the contract module itself, and the lowerers (`src/ir/lower/`),
// which recognise the source spelling and turn it into an `op`.
//
// WAIVERS ratchet: each names a file and the exact number of matching lines in
// it, with the reason.  A count that no longer matches (the site moved, was
// fixed, or a new one appeared) fails the census, so the list can only shrink
// honestly.
// ---------------------------------------------------------------------------

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const SRC = path.join(repoRoot, "src");

const VERBS = "getById|findById|findAll";
const COMPARE = new RegExp(
  `\\b(?:\\w*method|\\w*member|\\w*verb)\\s*[!=]==\\s*"(?:${VERBS})"`,
  "i",
);
const SET_LITERAL = new RegExp(`new Set\\(\\[[^\\]]*"(?:${VERBS})"`);

const EXEMPT_FILES = new Set(["src/util/repository-contract.ts"]);
const EXEMPT_DIRS = ["src/ir/lower/", "src/language/generated/"];

type Waiver = { count: number; reason: string; blockedBy?: string };

/** The e2e test client's HTTP verbs (`api.<agg>.getById(id)`, `ui.<agg>.getById`)
 *  name the generated by-id ROUTE, not a repository call; they are the API
 *  surface's vocabulary and do not ride the repository contract. */
const E2E_API_VERB =
  "e2e test-client verb: names the generated HTTP by-id route, not a repository call";

const WAIVERS: Record<string, Waiver> = {
  "src/ir/validate/checks/test-checks.ts": { count: 2, reason: E2E_API_VERB },
  "src/ir/validate/checks/e2e-route-checks.ts": { count: 3, reason: E2E_API_VERB },
  "src/system/e2e-render.ts": { count: 1, reason: E2E_API_VERB },
  "src/system/ui-e2e-render.ts": { count: 2, reason: E2E_API_VERB },
  "src/language/typing/elaborate.ts": {
    count: 2,
    reason:
      "the e2e test client's verbs and the ui data-handle path (`Ctx.Agg.findAll`), both API-surface vocabularies",
  },
};

function walk(dir: string, out: string[]): void {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (e.name.endsWith(".ts") && !e.name.endsWith(".d.ts")) out.push(p);
  }
}

/** Strip `//` line comments and `/* … *\/` block comments, keeping line
 *  structure.  String contents are preserved (the detector reads them). */
function stripComments(src: string): string {
  let out = "";
  let i = 0;
  let inBlock = false;
  let quote: string | undefined;
  while (i < src.length) {
    const c = src[i]!;
    const n = src[i + 1];
    if (inBlock) {
      if (c === "*" && n === "/") {
        inBlock = false;
        i += 2;
        continue;
      }
      out += c === "\n" ? "\n" : " ";
      i++;
      continue;
    }
    if (quote) {
      out += c;
      if (c === "\\") {
        out += n ?? "";
        i += 2;
        continue;
      }
      if (c === quote) quote = undefined;
      i++;
      continue;
    }
    if (c === "/" && n === "*") {
      inBlock = true;
      i += 2;
      continue;
    }
    if (c === "/" && n === "/") {
      while (i < src.length && src[i] !== "\n") i++;
      continue;
    }
    if (c === '"' || c === "'" || c === "`") quote = c;
    out += c;
    i++;
  }
  return out;
}

/** The matching lines of one file's source. */
function siteLines(rel: string, src: string): string[] {
  const out: string[] = [];
  stripComments(src)
    .split("\n")
    .forEach((line, idx) => {
      if (COMPARE.test(line) || SET_LITERAL.test(line)) {
        out.push(`${rel}:${idx + 1}: ${line.trim()}`);
      }
    });
  return out;
}

/** Every matching line, per repo-relative file. */
function censusSites(files: readonly string[]): Map<string, string[]> {
  const hits = new Map<string, string[]>();
  for (const abs of files) {
    const rel = path.relative(repoRoot, abs).split(path.sep).join("/");
    if (EXEMPT_FILES.has(rel) || EXEMPT_DIRS.some((d) => rel.startsWith(d))) continue;
    const lines = siteLines(rel, fs.readFileSync(abs, "utf8"));
    if (lines.length > 0) hits.set(rel, lines);
  }
  return hits;
}

describe("repository-verb census", () => {
  const files: string[] = [];
  walk(SRC, files);
  const hits = censusSites(files);

  it("no module outside the contract and the lowerers dispatches on a verb spelling", () => {
    const unwaived = [...hits.entries()]
      .filter(([file]) => !WAIVERS[file])
      .flatMap(([, lines]) => lines);
    expect(
      unwaived,
      "dispatch on the IR `op` or ask `src/util/repository-contract.ts` instead",
    ).toEqual([]);
  });

  it("every waiver matches its file's current count exactly (ratchet)", () => {
    const stale = Object.entries(WAIVERS)
      .filter(([file, w]) => (hits.get(file)?.length ?? 0) !== w.count)
      .map(([file, w]) => `${file}: waived ${w.count}, found ${hits.get(file)?.length ?? 0}`);
    expect(stale).toEqual([]);
  });

  it("every waiver gives a reason", () => {
    for (const [file, w] of Object.entries(WAIVERS)) {
      expect(w.reason.length, file).toBeGreaterThan(20);
    }
  });

  it("the detector sees a seeded dispatch and ignores a comment", () => {
    const seeded = siteLines(
      "seed.ts",
      [
        `// if (st.method === "getById") — a comment, not a site`,
        `if (st.method === "getById") go(); /* "findAll" */`,
        `const READS = new Set(["findById", "x"]);`,
        `if (e.member !== "findAll") stop();`,
        `if (o.kind === "getById") api();`,
      ].join("\n"),
    );
    expect(seeded.map((l) => l.split(":")[1])).toEqual(["2", "3", "4"]);
  });
});
