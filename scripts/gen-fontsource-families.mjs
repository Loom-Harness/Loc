#!/usr/bin/env node
// Regenerates src/util/fontsource-families.ts.
//
// A font a `theme {}` names is bundled with the generated app from its
// Fontsource npm package (`@fontsource/<id>`), so the generator needs every
// family Fontsource publishes, its package id, the static weights the package
// ships, and the version to pin.  The family list comes from the Fontsource
// API; the version is each package's npm `latest`.  A family the API lists
// whose package is not on npm is left out: it cannot be bundled.
//
// Usage: node scripts/gen-fontsource-families.mjs

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(root, "src/util/fontsource-families.ts");
const API = "https://api.fontsource.org/v1/fonts";
const REGISTRY = "https://registry.npmjs.org";
const CONCURRENCY = 32;

async function json(url) {
  for (let attempt = 1; ; attempt++) {
    const res = await fetch(url);
    if (res.status === 404) return undefined;
    if (res.ok) return res.json();
    if (attempt >= 4) throw new Error(`${url}: HTTP ${res.status}`);
    await new Promise((r) => setTimeout(r, 500 * attempt));
  }
}

const fonts = await json(API);
if (!Array.isArray(fonts) || fonts.length === 0) throw new Error("fontsource API: no fonts");

const versions = new Map();
let next = 0;
await Promise.all(
  Array.from({ length: CONCURRENCY }, async () => {
    while (next < fonts.length) {
      const { id } = fonts[next++];
      const latest = await json(`${REGISTRY}/@fontsource%2f${id}/latest`);
      if (latest?.version) versions.set(id, latest.version);
    }
  }),
);

// The version most packages are at is the default; an entry spells its own
// only when it differs.
const counts = new Map();
for (const v of versions.values()) counts.set(v, (counts.get(v) ?? 0) + 1);
const defaultVersion = [...counts].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1))[0][0];

const rows = fonts
  .filter((f) => versions.has(f.id))
  .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
  .map((f) => {
    // A family with no upright style is loaded through its package's default
    // stylesheet, so it lists no weights.
    const weights = f.styles.includes("normal")
      ? [...new Set(f.weights)]
          .sort((a, b) => a - b)
          .map((w) => String(w / 100))
          .join("")
      : "";
    const v = versions.get(f.id);
    const cells = [f.family, weights, ...(v === defaultVersion ? [] : [v])];
    return `  ${JSON.stringify(f.id)}: ${JSON.stringify(cells).replaceAll(",", ", ")},`;
  });
const skipped = fonts.filter((f) => !versions.has(f.id)).map((f) => f.id);

const out = `// GENERATED by scripts/gen-fontsource-families.mjs — do not edit by hand.
//
// Every font family Fontsource publishes as an npm package (\`@fontsource/<id>\`):
// the families a \`theme {}\` font can name and the generator can bundle.
// Source: ${API} and each package's npm \`latest\`.
// Listed by the API but not on npm, so left out: ${skipped.length ? skipped.join(", ") : "none"}.

/** The version every package is pinned at unless its entry names its own. */
export const FONTSOURCE_DEFAULT_VERSION = ${JSON.stringify(defaultVersion)};

/** Package id → [family, the upright static weights in hundreds ("4" is 400;
 *  empty for a family with no upright style), version when it is not
 *  \`FONTSOURCE_DEFAULT_VERSION\`]. */
export const FONTSOURCE_FAMILIES: Readonly<
  Record<string, readonly [family: string, weights: string, version?: string]>
> = {
${rows.join("\n")}
};
`;
writeFileSync(outFile, out);
// The repo formatter owns the layout (it unquotes the plain-identifier keys).
execFileSync("npx", ["biome", "format", "--write", outFile], { cwd: root, stdio: "inherit" });
console.log(
  `wrote ${outFile}: ${rows.length} families, default version ${defaultVersion}, ${skipped.length} skipped`,
);
