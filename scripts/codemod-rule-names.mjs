// Codemod for #4450: `message "…"` leaves the model.  A rule is NAMED
// (`invariant nameRequired: …`) and its English text moves to the translator
// tree, `locales/en/<Ctx>.json`, under the rule's identity key
// `<Owner>.rule.<name>` (the file name carries the context).
//
//   node scripts/codemod-rule-names.mjs [--check] [--list] [--locales <dir>] <path>...
//
//   <path>      a `.ddd` file or a directory (walked recursively for `*.ddd`,
//               skipping node_modules / .git / dist / out / .loom).  Defaults
//               to `.`.
//   --check     write nothing; exit 1 when any file still carries a
//               `message "…"` clause.
//   --list      write nothing; print the files that would change.
//   --locales   the translator-tree root (default: `locales/` next to each
//               `.ddd`, the same default `ddd generate` and `ddd i18n` read).
//
// For every `message "X"` on an `invariant`, a field `check` or a
// `precondition`, a rule WITHOUT a name gets `deriveRuleName(X)` — the first
// four non-filler words of X in camelCase, deduplicated against every other
// rule name of the same owner — and the clause is deleted.  A rule that already
// has a name keeps it.  X is written to `locales/en/<Ctx>.json` (`_system.json`
// for a rule outside every context), merged into what is there.
//
// The derivation is the compiler's own (`src/util/rule-name.ts`, pinned equal
// by `test/scripts/codemod-rule-names.test.ts`): until the corpus is migrated
// the compiler names a messaged rule exactly this way, so running the codemod
// changes no generated byte.
//
// Text-level and conservative, like the sibling codemods: comments and
// formatting survive byte-for-byte outside the rewritten clauses.  It is
// comment- and string-aware.  The owner of a rule is the innermost enclosing
// `aggregate` / `valueobject` / `commandHandler` / `queryHandler` / `workflow` /
// `domainService` block; an entity part's rules belong to its aggregate.

import { promises as fs } from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const SKIP_DIRS = new Set(["node_modules", ".git", "dist", "out", ".loom"]);

// --- the derivation (mirror of src/util/rule-name.ts) ----------------------

export const RULE_NAME_MAX_WORDS = 4;
const FILLER = new Set(["a", "an", "the", "is", "are", "be", "must", "should", "been"]);

export function deriveRuleName(text) {
  const all = text.toLowerCase().match(/[a-z0-9]+/g) ?? [];
  const kept = all.filter((w) => !FILLER.has(w));
  const words = (kept.length > 0 ? kept : all).slice(0, RULE_NAME_MAX_WORDS);
  if (words.length === 0 || !/^[a-z]/.test(words[0])) words.unshift("rule");
  if (words.length === 1) words.push("rule");
  return words.map((w, i) => (i === 0 ? w : w[0].toUpperCase() + w.slice(1))).join("");
}

export function dedupeRuleName(name, taken) {
  let out = name;
  for (let n = 2; taken.has(out); n++) out = `${name}${n}`;
  taken.add(out);
  return out;
}

// --- scanning ----------------------------------------------------------------

/** Tokens of `src`, comments skipped: identifiers, `"…"` strings, and single
 *  punctuation chars, each with its offsets.  `.ddd` has `//` line comments,
 *  `/* … *\/` block comments and double-quoted strings with backslash
 *  escapes. */
function tokens(src) {
  const out = [];
  let i = 0;
  while (i < src.length) {
    const c = src[i];
    const n = src[i + 1];
    if (c === "/" && n === "/") {
      while (i < src.length && src[i] !== "\n") i++;
    } else if (c === "/" && n === "*") {
      const end = src.indexOf("*/", i + 2);
      i = end < 0 ? src.length : end + 2;
    } else if (c === '"') {
      let j = i + 1;
      while (j < src.length && src[j] !== '"') j += src[j] === "\\" ? 2 : 1;
      out.push({ kind: "str", text: src.slice(i, j + 1), start: i, end: j + 1 });
      i = j + 1;
    } else if (/\s/.test(c)) {
      i++;
    } else if (/[A-Za-z_]/.test(c)) {
      let j = i;
      while (j < src.length && /[A-Za-z0-9_]/.test(src[j])) j++;
      out.push({ kind: "id", text: src.slice(i, j), start: i, end: j });
      i = j;
    } else {
      out.push({ kind: "punct", text: c, start: i, end: i + 1 });
      i++;
    }
  }
  return out;
}

const OWNER_KINDS = new Set([
  "aggregate",
  "valueobject",
  "commandHandler",
  "queryHandler",
  "workflow",
  "domainService",
]);
const RULE_KEYWORDS = new Set(["invariant", "check", "precondition"]);

/** Every rule in `src`: its keyword token, its owner / context, its declared
 *  name, and its `message "…"` clause when it has one. */
export function findRules(src) {
  const toks = tokens(src);
  const stack = []; // { kind, name } per open brace
  let pending = null;
  const rules = [];
  let current = null; // the rule whose clause tail we are inside
  for (let k = 0; k < toks.length; k++) {
    const t = toks[k];
    if (t.kind === "id" && (OWNER_KINDS.has(t.text) || t.text === "context")) {
      const next = toks[k + 1];
      if (next && next.kind === "id") pending = { kind: t.text, name: next.text };
      continue;
    }
    if (t.kind === "punct" && t.text === "{") {
      stack.push(pending ?? { kind: null, name: null });
      pending = null;
      continue;
    }
    if (t.kind === "punct" && t.text === "}") {
      stack.pop();
      current = null;
      continue;
    }
    if (t.kind === "id" && RULE_KEYWORDS.has(t.text)) {
      const owner = [...stack].reverse().find((f) => OWNER_KINDS.has(f.kind));
      const ctx = [...stack].reverse().find((f) => f.kind === "context");
      const a = toks[k + 1];
      const b = toks[k + 2];
      const named =
        a?.kind === "id" && b?.kind === "punct" && b.text === ":" && toks[k + 3]?.text !== ":";
      current = {
        keyword: t,
        ownerFrame: owner ?? null,
        owner: owner?.name ?? null,
        ctx: ctx?.name ?? null,
        declared: named ? a.text : undefined,
        message: undefined,
      };
      rules.push(current);
      continue;
    }
    if (t.kind === "id" && t.text === "message" && current && current.message === undefined) {
      const s = toks[k + 1];
      if (s?.kind === "str") {
        current.message = {
          start: t.start,
          end: s.end,
          text: JSON.parse(s.text),
        };
        current = null;
      }
    }
  }
  return rules;
}

/** Rewrite `src`: name every messaged rule and drop its clause.  Returns the
 *  new text and the `locales/en` entries, `{ ns, key, text }`. */
export function migrateRuleMessages(src) {
  const rules = findRules(src);
  const takenByOwner = new Map();
  const taken = (r) => {
    const k = r.ownerFrame ?? "__none__";
    if (!takenByOwner.has(k)) takenByOwner.set(k, new Set());
    return takenByOwner.get(k);
  };
  for (const r of rules) if (r.declared !== undefined) taken(r).add(r.declared);
  const edits = [];
  const entries = [];
  for (const r of rules) {
    if (!r.message) continue;
    if (r.message.text.trim() === "") continue;
    const name = r.declared ?? dedupeRuleName(deriveRuleName(r.message.text), taken(r));
    if (r.declared === undefined) edits.push({ at: r.keyword.end, del: 0, ins: ` ${name}:` });
    // Drop ` message "…"` with the whitespace before it.
    let from = r.message.start;
    while (from > 0 && /[ \t]/.test(src[from - 1])) from--;
    edits.push({ at: from, del: r.message.end - from, ins: "" });
    entries.push({
      ns: r.ctx ?? "_system",
      key: `${r.owner ?? "_"}.rule.${name}`,
      text: r.message.text,
    });
  }
  edits.sort((x, y) => y.at - x.at);
  let text = src;
  for (const e of edits) text = text.slice(0, e.at) + e.ins + text.slice(e.at + e.del);
  return { text, entries, changed: entries.length };
}

// --- CLI -----------------------------------------------------------------------

async function* walk(p) {
  const st = await fs.stat(p);
  if (st.isFile()) {
    if (p.endsWith(".ddd")) yield p;
    return;
  }
  for (const e of await fs.readdir(p, { withFileTypes: true })) {
    if (e.isDirectory() && SKIP_DIRS.has(e.name)) continue;
    yield* walk(path.join(p, e.name));
  }
}

async function mergeLocale(file, entries) {
  let current = {};
  try {
    current = JSON.parse(await fs.readFile(file, "utf8"));
  } catch {
    current = {};
  }
  for (const { key, text } of entries) current[key] = text;
  const sorted = Object.fromEntries(
    Object.keys(current)
      .sort()
      .map((k) => [k, current[k]]),
  );
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, `${JSON.stringify(sorted, null, 2)}\n`);
}

async function main(argv) {
  const check = argv.includes("--check");
  const list = argv.includes("--list");
  const li = argv.indexOf("--locales");
  const localesRoot = li >= 0 ? argv[li + 1] : undefined;
  const roots = argv.filter((a, i) => !a.startsWith("--") && (li < 0 || i !== li + 1));
  let pending = 0;
  for (const root of roots.length > 0 ? roots : ["."]) {
    for await (const file of walk(root)) {
      const src = await fs.readFile(file, "utf8");
      const { text, entries, changed } = migrateRuleMessages(src);
      if (changed === 0) continue;
      pending++;
      if (check || list) {
        console.log(file);
        continue;
      }
      await fs.writeFile(file, text);
      const base = localesRoot ?? path.join(path.dirname(file), "locales");
      const byNs = new Map();
      for (const e of entries) byNs.set(e.ns, [...(byNs.get(e.ns) ?? []), e]);
      for (const [ns, es] of byNs) await mergeLocale(path.join(base, "en", `${ns}.json`), es);
      console.log(`${file}: ${changed} rule(s) named`);
    }
  }
  if (check && pending > 0) process.exitCode = 1;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  await main(process.argv.slice(2));
}
