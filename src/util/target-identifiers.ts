// ---------------------------------------------------------------------------
// The per-target reserved-identifier contract — ONE table, ONE escaping path.
//
// A `.ddd` name is Loom-legal and may still be fatal in a target: `def` /
// `lambda` in python (#3102), `base` / `event` in C#, `end` / `do` in elixir,
// `member` in F#, `break` / `eval` as a TS parameter, `then` as a TS method
// (it makes every aggregate a thenable).  Every backend used to carry its own
// keyword set beside its own escape helper — five in `naming.ts`, a drifted
// Java copy in `java/naming.ts` (it had `record`/`yield`/`sealed`/`permits`,
// `naming.ts` did not), F#'s in `feliz/fs-ident.ts`, none for Dart — so a word
// one table knew and another did not was escaped on one backend and fatal on
// the next.  They are now views of {@link RESERVED}; every `escape<Lang>Ident`
// delegates to {@link escapeTargetIdent}.
//
// Ruling D-TARGET-RESERVED-NAMES (docs/decisions.md): escape per backend,
// never refuse.  The escape is visible only in generated HOST source; the wire
// key, the OpenAPI schema and the stored column keep the declared name.
//
// The gate is `test/fixtures/corpus/target-reserved-words.ddd`, which names a
// field, an enum value, an operation and its parameter after every entry here
// that the `.ddd` grammar admits, on every backend's compile leg;
// `test/util/target-identifiers.test.ts` fails when a table entry the grammar
// admits is missing from that fixture, and checks the tables that have an
// authoritative source runnable in CI against it (python's `keyword` module,
// the TypeScript scanner).
// ---------------------------------------------------------------------------

