/** How each target spells a reserved word as an identifier: C#'s verbatim
 *  `@base`, F#'s double-backtick ``member``, a trailing underscore
 *  everywhere else (`def_`, `end_`, `break_`). */
const ESCAPE: Record<IdentTarget, (name: string) => string> = {
  ts: (n) => `${n}_`,
  csharp: (n) => `@${n}`,
  java: (n) => `${n}_`,
  python: (n) => `${n}_`,
  elixir: (n) => `${n}_`,
  fsharp: (n) => `\`\`${n}\`\``,
  dart: (n) => `${n}_`,
};

/** True when `name` cannot be spelled as a bare identifier in `target`. */
export function isReserved(target: IdentTarget, name: string): boolean {
  return RESERVED[target].has(name);
}

/** THE escaping path: `name`, spelled so `target` accepts it as an
 *  identifier.  A non-reserved name passes through byte-identically. */
export function escapeTargetIdent(target: IdentTarget, name: string): string {
  return RESERVED[target].has(name) ? ESCAPE[target](name) : name;
}

/** The reserved words of `target`, sorted — for the census and docs. */
export function reservedWords(target: IdentTarget): readonly string[] {
  return [...RESERVED[target]].sort();
}

/** Names a target reserves as a CLASS MEMBER although they are legal
 *  bindings.  TS: a method named `constructor` IS the constructor, and a
 *  method named `then` makes every instance a thenable, so `await
 *  repo.getById(...)` resolves to whatever `then` does (TS1320).  Escaped
 *  with a trailing underscore at the member declaration and every call. */
const RESERVED_MEMBERS: Partial<Record<IdentTarget, ReadonlySet<string>>> = {
  ts: new Set(["constructor", "then"]),
};

/** `name` as a class-member name in `target`. */
export function escapeTargetMember(target: IdentTarget, name: string): string {
  return RESERVED_MEMBERS[target]?.has(name) ? `${name}_` : name;
}
