// (`../_imports/java.ts`).
//
// `JAVA_LANG_TYPES`: the public types of `java.lang` (JDK 25 `java.base`), in
// scope in every unit without an import.  A unit cannot un-import them, so a
// domain type of one of these names is spelled fully qualified wherever the
// generated code references it through the plan.
//
// `JAVA_FRAMEWORK_PACKAGES`: the public top-level types of each framework
// package an emitter may write as an on-demand import (`import <pkg>.*;`).  No
// generated unit keeps an on-demand import: the finalizer replaces one with a
// single-type import of each listed type the unit's text names.  Sources:
// jakarta.persistence-api 3.2.0 and spring-web 7.0.8, the versions the
// generated Gradle build resolves.  `JAVA_FRAMEWORK_STATIC_MEMBERS` is the same
// for `import static <class>.*;`.

