// ---------------------------------------------------------------------------
// `app/http/security_headers.py` — the FastAPI half of the shared baseline
// security headers (`src/util/security-headers.ts`).
//
// A pure ASGI middleware rather than `BaseHTTPMiddleware`: it only rewrites the
// `http.response.start` message, so a streamed body (the realtime SSE route, a
// file download) passes through untouched.  main.py adds it last, which makes
// it the outermost user middleware — every answer the app and the other
// middlewares produce (401s, 415s, problem documents, /docs, the embedded SPA)
// goes out through it.
// ---------------------------------------------------------------------------

import { lines } from "../../util/code-builder.js";
import {
  BASELINE_SECURITY_HEADERS,
  HSTS_HEADER,
  SECURE_TRANSPORT_ENV,
  SECURE_TRANSPORT_OFF_VALUES,
} from "../../util/security-headers.js";

const pyBytes = (s: string): string => `b${JSON.stringify(s)}`;

/** Render `app/http/security_headers.py`. */
export function renderPySecurityHeaders(): string {
  const offValues = SECURE_TRANSPORT_OFF_VALUES.map((v) => JSON.stringify(v)).join(", ");
  return `${lines(
    `"""Baseline security headers on every response.`,
    "",
    "Auto-generated by Loom.  Pin via .loomignore to customise.",
    "",
    `Strict-Transport-Security only while ${SECURE_TRANSPORT_ENV} is on (the default);`,
    "the local compose stack serves plain http and turns it off.",
    `"""`,
    "",
    "import os",
    "",
    "from starlette.types import ASGIApp, Message, Receive, Scope, Send",
    "",
    `SECURE_TRANSPORT = os.getenv(${JSON.stringify(SECURE_TRANSPORT_ENV)}, "").strip().lower() not in (${offValues})`,
    "",
    "_HEADERS: list[tuple[bytes, bytes]] = [",
    ...BASELINE_SECURITY_HEADERS.map(
      ([name, value]) => `    (${pyBytes(name.toLowerCase())}, ${pyBytes(value)}),`,
    ),
    "]",
    "if SECURE_TRANSPORT:",
    `    _HEADERS.append((${pyBytes(HSTS_HEADER[0].toLowerCase())}, ${pyBytes(HSTS_HEADER[1])}))`,
    "_NAMES = {name for name, _ in _HEADERS}",
    "",
    "",
    "class SecurityHeadersMiddleware:",
    "    def __init__(self, app: ASGIApp) -> None:",
    "        self.app = app",
    "",
    "    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:",
    '        if scope["type"] != "http":',
    "            await self.app(scope, receive, send)",
    "            return",
    "",
    "        async def send_with_headers(message: Message) -> None:",
    '            if message["type"] == "http.response.start":',
    "                kept = [",
    "                    (name, value)",
    '                    for name, value in message.get("headers", [])',
    "                    if name.lower() not in _NAMES",
    "                ]",
    '                message = {**message, "headers": kept + _HEADERS}',
    "            await send(message)",
    "",
    "        await self.app(scope, receive, send_with_headers)",
  )}\n`;
}
