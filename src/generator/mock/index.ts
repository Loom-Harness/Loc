// ---------------------------------------------------------------------------
// The `mock` target's project: a dependency-free Node HTTP server.
//
// A mock deployable stands in for a backend at the api contract: it runs no
// domain logic and owns no database.  The server answers the orchestrator's
// probe (`GET /health`) and refuses every other request with `501` and an
// RFC 9457 problem-details body, so a frontend targeting it gets a
// well-formed error rather than a hung or reset connection.
//
// The project has no dependencies and no build step: the image copies the
// two files and runs `node server.mjs`.
// ---------------------------------------------------------------------------

import type { DeployableIR } from "../../ir/types/loom-ir.js";
import { lines } from "../../util/code-builder.js";
import { NODE_RUNTIME_IMAGE } from "../../util/node-image.js";
import { serviceSlug } from "../../util/service-slug.js";

/** The port the mock server listens on inside its container when `PORT` is
 *  unset.  Compose publishes the deployable's port onto it. */
export const MOCK_LISTEN_PORT = 3000;

/** The probe path the server answers with `200`. */
export const MOCK_HEALTH_PATH = "/health";

/** `server.mjs` — answers the probe and refuses everything else.  `start` is
 *  exported so a caller can run the server in-process on a port of its
 *  choosing; run as the entry point, it listens on `PORT`. */
function renderServer(deployable: DeployableIR): string {
  return lines(
    "// Auto-generated by Loom: the mock target.",
    `// Deployable \`${deployable.name}\` answers ${MOCK_HEALTH_PATH} and refuses every other`,
    "// request with 501 and a problem-details body.",
    'import { createServer } from "node:http";',
    'import { pathToFileURL } from "node:url";',
    "",
    `const DEPLOYABLE = ${JSON.stringify(deployable.name)};`,
    `const DEFAULT_PORT = ${MOCK_LISTEN_PORT};`,
    "",
    "function send(res, status, contentType, body) {",
    "  const text = JSON.stringify(body);",
    "  res.writeHead(status, {",
    '    "content-type": contentType,',
    '    "content-length": Buffer.byteLength(text),',
    "  });",
    "  res.end(text);",
    "}",
    "",
    "export function handle(req, res) {",
    '  const path = (req.url ?? "/").split("?")[0];',
    `  if ((req.method === "GET" || req.method === "HEAD") && path === ${JSON.stringify(MOCK_HEALTH_PATH)}) {`,
    '    send(res, 200, "application/json", { status: "ok" });',
    "    return;",
    "  }",
    '  send(res, 501, "application/problem+json", {',
    '    type: "about:blank",',
    '    title: "Not Implemented",',
    "    status: 501,",
    "    detail: `The mock deployable ${DEPLOYABLE} has no handler for ${req.method} ${path}.`,",
    "  });",
    "}",
    "",
    "export function start(port = Number(process.env.PORT ?? DEFAULT_PORT)) {",
    "  const server = createServer(handle);",
    "  server.listen(port, () => {",
    "    const { port: bound } = server.address();",
    "    console.log(`mock ${DEPLOYABLE} listening on ${bound}`);",
    "  });",
    "  return server;",
    "}",
    "",
    "if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {",
    "  const server = start();",
    '  for (const signal of ["SIGINT", "SIGTERM"]) {',
    "    process.on(signal, () => server.close(() => process.exit(0)));",
    "  }",
    "}",
    "",
  );
}

function renderPackageJson(deployable: DeployableIR): string {
  const pkg = {
    name: serviceSlug(deployable.name),
    version: "0.0.0",
    private: true,
    type: "module",
    scripts: { start: "node server.mjs" },
  };
  return `${JSON.stringify(pkg, null, 2)}\n`;
}

function renderDockerfile(): string {
  return lines(
    "# syntax=docker/dockerfile:1",
    "# Auto-generated.",
    "",
    `FROM ${NODE_RUNTIME_IMAGE}`,
    "WORKDIR /app",
    `ENV NODE_ENV=production PORT=${MOCK_LISTEN_PORT}`,
    "COPY package.json server.mjs ./",
    "# Run unprivileged: the base image's `node` user (uid 1000), by number so a",
    "# k8s `runAsNonRoot` check can verify it.",
    "USER 1000:1000",
    `EXPOSE ${MOCK_LISTEN_PORT}`,
    'CMD ["node", "server.mjs"]',
    "",
  );
}

/** Every file of one mock deployable's project, keyed by path relative to
 *  the deployable's folder. */
export function generateMockProject(args: { deployable: DeployableIR }): Map<string, string> {
  const { deployable } = args;
  return new Map([
    ["package.json", renderPackageJson(deployable)],
    ["server.mjs", renderServer(deployable)],
    ["Dockerfile", renderDockerfile()],
  ]);
}
