import type { MigrationStep, MigrationsIR } from "../../../ir/types/migrations-ir.js";
import { splitTransactionalSteps } from "../../../ir/util/migration-steps.js";
import { lines } from "../../../util/code-builder.js";
import { renderPgStep } from "../../sql-pg.js";

// ---------------------------------------------------------------------------
// MigrationsIR → Flyway-style versioned SQL under
// `src/main/resources/db/migration/`.  The steps are rendered by the
// shared Postgres-SQL renderer (`src/generator/sql-pg.ts`) — Java only
// translates `MigrationStep[]` into files; it never re-derives schema.
//
// Version scheme: `V<version>.<n>__<Module>_<Name>.sql` — `<version>` is
// the generation's migration-chain version (unique across modules and
// strictly increasing, so Flyway never sees a version below one it has
// already applied) and `<n>` the module's index within the deployable.
//
// A generation's non-transactional unit (`CREATE INDEX CONCURRENTLY`,
// `splitTransactionalSteps`) is its own script, `V<version>.<n>.1__…Concurrent`,
// which Flyway orders right after `V<version>.<n>` and records on its own.
// Flyway's Postgres parser recognises `CREATE INDEX CONCURRENTLY` /
// `DROP INDEX CONCURRENTLY` as statements that cannot run in a transaction
// and applies a script holding only such statements without one; a script
// MIXING them with transactional statements is refused, which is why the unit
// is a script of its own.
// ---------------------------------------------------------------------------

export function emitJavaMigrations(migrations: MigrationsIR[], out: Map<string, string>): void {
  migrations.forEach((m, i) => {
    if (m.steps.length === 0) return;
    const script = (steps: readonly MigrationStep[]): string =>
      lines(
        `-- Auto-generated by Loom for module ${m.module} — do not edit by hand.`,
        `-- Derived from the shared MigrationsIR (see docs/migrations.md).`,
        ``,
        ...steps.map((s) => renderPgStep(s)),
        ``,
      );
    const { transactional, nonTransactional } = splitTransactionalSteps(m.steps);
    const stem = `${sanitize(m.module)}_${sanitize(m.name)}`;
    if (transactional.length > 0) {
      out.set(
        `src/main/resources/db/migration/V${m.version}.${i + 1}__${stem}.sql`,
        script(transactional),
      );
    }
    if (nonTransactional.length > 0) {
      out.set(
        `src/main/resources/db/migration/V${m.version}.${i + 1}.1__${stem}Concurrent.sql`,
        script(nonTransactional),
      );
    }
  });
}

/** Flyway descriptions: word characters only (anything else would shift
 *  the `__` separator parse). */
function sanitize(s: string): string {
  return s.replace(/[^A-Za-z0-9]/g, "");
}
