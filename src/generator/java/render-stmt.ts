// ---------------------------------------------------------------------------
// Statement LEAF TABLE for the Java / Spring backend.  The 11-kind `StmtIR`
// dispatch, the chunk/join pair and the `variant-match` guard live once in
// `../_stmt/target.ts`; this file supplies only the per-kind spelling (audit
// finding C1).  Bodies render inside aggregate methods at two indent levels.
// ---------------------------------------------------------------------------

const INDENT = "        ";
const DEFAULT_CTX: JavaRenderContext = { thisName: "this" };

/** Compile-time --trace context — mirrors render-stmt.ts on the C# side.
 *  When `emitTrace` is false the renderer is byte-identical to its
 *  pre-trace output. */
export interface JavaTraceCtx {
  emitTrace: boolean;
  aggregate: string;
  op: string;
  /** True when rendering a body on an event-sourced aggregate: `emit`
   *  records the event AND folds it via `_apply(ev)` so in-memory state
   *  reflects the transition before the command returns. */
  eventSourced?: boolean;
  /** True when rendering an aggregate OPERATION body: a named
   *  `precondition` then throws its wire code and pointer too (M-T1.11 (c)). */
  domainFloorCodes?: boolean;
}

const NO_TRACE: JavaTraceCtx = { emitTrace: false, aggregate: "", op: "" };

export function renderJavaStatements(
  stmts: StmtIR[],
  ctx: JavaRenderContext = DEFAULT_CTX,
  traceCtx: JavaTraceCtx = NO_TRACE,
): string {
  return renderStmtsWith(stmts, javaStmtTarget(withBodyLets(stmts, ctx), traceCtx));
}

/** Same rendering as `renderJavaStatements`, but one (possibly multi-line)
 *  string per statement instead of the pre-joined whole — exactly the map
 *  `renderJavaStatements` joins with `"\n"` today, so `chunks.join("\n")` is
 *  byte-identical to it.  Lets a caller that owns the final file content
 *  (the entity emitter) recover each statement's own line span inside an
 *  operation body for `SourceMapRecorder.fragment` — see
 *  `statementSubRegions` (re-exported below). */
export function renderJavaStatementChunks(
  stmts: StmtIR[],
  ctx: JavaRenderContext = DEFAULT_CTX,
  traceCtx: JavaTraceCtx = NO_TRACE,
): string[] {
  return renderStmtChunksWith(stmts, javaStmtTarget(withBodyLets(stmts, ctx), traceCtx));
}

/** `ctx` with every `let` the body declares (in its declared Java spelling)
 *  added to the lambda scope — a `tags.where(x => …)` after (or inside the
 *  initializer of) a `let x` would otherwise redeclare it. */
function withBodyLets(stmts: StmtIR[], ctx: JavaRenderContext): JavaRenderContext {
  const names: string[] = [];
  for (const s of stmts) {
    walkStmtsDeep(s, (st) => {
      if (st.kind === "let") names.push(ctx.letExpr?.(st.name) ?? escapeJavaIdent(st.name));
    });
  }
  return withLambdaScope(ctx, names);
}

