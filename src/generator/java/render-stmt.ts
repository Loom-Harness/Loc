/** The Java leaf table.  Built per call so the arms close over the Java
 *  render context and the `--trace` context instead of threading them
 *  through the shared spine. */
function javaStmtTarget(ctx: JavaRenderContext, traceCtx: JavaTraceCtx): StmtTarget {
  return {
    backendName: "Java",
    // PRESERVED INCONSISTENCY (audit C1): java numbers statement temps by
    // POSITION in the body, python numbers them per-kind.  Normalising the two
    // moves generated bytes, so it stays a separate, deliberately-gated change.
    indexing: "positional",

    precondition: (s, ix) => precondition(s.expr, s.source, s.message, ix.pre, ctx, traceCtx),

    requires: (s) =>
      // Authorization gate — ForbiddenException maps to 403 in the
      // controller advice.
      `${INDENT}if (!(${renderJavaExpr(s.expr, ctx)})) throw new ForbiddenException(${JSON.stringify(`Forbidden: ${s.source}`)});`,

    let: (s) =>
      // `let`-names may collide with a Java keyword; escape consistently with
      // the matching `refKind: "let"` use sites (`let class` → `class_`).
      // (or the collision-safe local the caller's `letExpr` assigned).
      `${INDENT}var ${ctx.letExpr?.(s.name) ?? escapeJavaIdent(s.name)} = ${renderJavaExpr(s.expr, ctx)};`,

    assign: (s, ix) => {
      // A collection field assigned from another collection takes a mutable
      // copy: the source may be an immutable list (`Stream.toList()`, `List.of`),
      // and a later `field += v` appends in place.
      const rhs = renderJavaExpr(s.value, ctx);
      const value = s.targetType.kind === "array" ? `new java.util.ArrayList<>(${rhs})` : rhs;
      const t = s.targetType;
      // A contained-part collection is an `orphanRemoval` association: Hibernate
      // refuses a REPLACED collection at flush ("no longer referenced by the
      // owning entity instance"), so `:=` replaces its CONTENTS in place —
      // copy the new elements first (the value usually reads the list it is
      // about to clear), then clear and refill.
      const base =
        t.kind === "array" && t.element.kind === "entity" && t.element.declKind === "part"
          ? `${INDENT}{ var __parts = ${value}; ${renderPath(s.target)}.clear(); ${renderPath(s.target)}.addAll(__parts); }`
          : `${INDENT}${renderPath(s.target)} = ${value};`;
      // NOTE the wrap ORDER: java (like .NET / python) puts `value_computed`
      // INSIDE the provenance capture; node puts it outside.  Preserved.
      return withProvCapture(
        withValueComputed(base, s.target, traceCtx),
        s.prov,
        s.target,
        s.value,
        ix.prov,
        ctx,
        s.targetType,
      );
    },

    add: (s, ix) => {
      const base = `${INDENT}${renderPath(s.target)}.add(${renderJavaExpr(s.value, ctx)});`;
      return withProvCapture(base, s.prov, s.target, s.value, ix.prov, ctx);
    },

    remove: (s, ix) => {
      // `xs -= v` removes every element equal to `v`.  `removeIf` compares
      // by value (`Objects.equals`), so an `int[]` (`List<Integer>`) element
      // never resolves to the `remove(int index)` overload.
      const value = renderJavaExpr(s.value, ctx);
      const base = `${INDENT}{ var __rm = ${value}; ${renderPath(s.target)}.removeIf(__e -> java.util.Objects.equals(__e, __rm)); }`;
      return withProvCapture(base, s.prov, s.target, s.value, ix.prov, ctx);
    },

    emit: (s) => {
      const args = orderedEventArgs(s, ctx);
      if (traceCtx.eventSourced) {
        return `${INDENT}{ var __ev = new ${s.eventName}(${args}); this._domainEvents.add(__ev); this._apply(__ev); }`;
      }
      return `${INDENT}this._domainEvents.add(new ${s.eventName}(${args}));`;
    },

    call: (s) => {
      const args = s.args.map((a) => renderJavaExpr(a, ctx)).join(", ");
      return `${INDENT}this.${jid(s.name)}(${args});`;
    },

    expression: (s) => `${INDENT}${renderJavaExpr(s.expr, ctx)};`,

    // `if (<cond>) { … } else { … }` — the branch bodies arrive rendered at
    // this table's own INDENT, so they shift one level here.
    if: (s, _ix, thenSrc, elseSrc) => {
      const head = `${INDENT}if (${renderJavaExpr(s.cond, ctx)}) {\n${indentNested(thenSrc, "    ")}\n${INDENT}}`;
      if (elseSrc === undefined) return head;
      return `${head} else {\n${indentNested(elseSrc, "    ")}\n${INDENT}}`;
    },

    // `switch (<subject>) { case <Union>_<Tag> b -> { … } … }` — an arrow
    // switch statement over the sealed union's carrier records; each case is
    // its own block, so two arms may bind the same name.  A pattern needs a
    // binder even when the arm reads none (an unnamed `_` is preview-only on
    // Java 21), and a scalar variant's binding reads its carrier's `value()`.
    // A pattern switch statement must be exhaustive: when the arms leave a
    // variant out and there is no `else`, an empty `default` completes it.
    variantMatch: (s, ix, m) => {
      const subject = renderJavaExpr(s.subject, ctx);
      const block = (head: string, decl: string | undefined, body: string): string =>
        [
          `${INDENT}    ${head} -> {`,
          ...(decl ? [`${INDENT}        ${decl}`] : []),
          ...(body ? [indentNested(body, "        ")] : []),
          `${INDENT}    }`,
        ].join("\n");
      const cases = m.arms.map((a, i) => {
        const carrier = `${m.unionName}_${a.tag}`;
        if (a.binding && !a.scalar) return block(`case ${carrier} ${a.binding}`, undefined, a.body);
        const binder = a.binding ? `${a.binding}Carrier` : `unused${ix.pre}_${i}`;
        return block(
          `case ${carrier} ${binder}`,
          a.binding ? `var ${a.binding} = ${binder}.value();` : undefined,
          a.body,
        );
      });
      if (m.else !== undefined) cases.push(block("default", undefined, m.else));
      else if (!m.exhaustive) cases.push(`${INDENT}    default -> { }`);
      return [`${INDENT}switch (${subject}) {`, ...cases, `${INDENT}}`].join("\n");
    },

    // `if (<subject> != null) { … } else { … }` — the arm bindings read the
    // subject itself.
    presenceMatch: (s, _ix, present, absent) => {
      const subject = renderJavaExpr(s.subject, ctx);
      const presentSrc = present ? `\n${indentNested(present, "    ")}` : "";
      const head = `${INDENT}if (${subject} != null) {${presentSrc}\n${INDENT}}`;
      if (absent === undefined) return head;
      return `${head} else {\n${indentNested(absent, "    ")}\n${INDENT}}`;
    },

    return: (s) => {
      // Exception-less tagged return → the domain union's variant record
      // `<Union>_<Tag>(…)`, args ordered by the variant's declared field
      // order.  Untagged returns render the value as-is.
      if (!s.variantTag || !ctx.returnUnion) {
        return `${INDENT}return ${renderJavaExpr(s.value, ctx)};`;
      }
      const variant = `${ctx.returnUnion.name}_${s.variantTag}`;
      if (s.variantShape === "none") return `${INDENT}return new ${variant}();`;
      if (s.variantShape === "scalar") {
        return `${INDENT}return new ${variant}(${renderJavaExpr(s.value, ctx)});`;
      }
      const member = ctx.returnUnion.members.find((m) => m.tag === s.variantTag);
      const objFields = s.value.kind === "object" ? s.value.fields : [];
      const order = member && member.shape === "record" ? member.fields : [];
      // `return this` in the aggregate's own arm: the record carries the
      // aggregate's fields, read through its accessors.
      if (s.value.kind === "this") {
        const reads = order.map((mf) => `this.${jid(mf.name)}()`);
        return `${INDENT}return new ${variant}(${reads.join(", ")});`;
      }
      const args = order.map((mf) => {
        const f = objFields.find((of) => of.name === mf.name);
        return f ? renderJavaExpr(f.value, ctx) : "null";
      });
      return `${INDENT}return new ${variant}(${args.join(", ")});`;
    },
  };
}

/** Java events are records with positional constructors — order the emit
 *  site's `name: value` pairs by the event's declared field order
 *  (`ctx.eventFields`), falling back to emit-site order when the entity
 *  emitter didn't thread the map (synthetic contexts). */
function orderedEventArgs(s: Extract<StmtIR, { kind: "emit" }>, ctx: JavaRenderContext): string {
  const declared = ctx.eventFields?.get(s.eventName);
  const rendered = new Map(s.fields.map((f) => [f.name, renderJavaExpr(f.value, ctx)]));
  if (!declared) return [...rendered.values()].join(", ");
  return declared.map((name) => rendered.get(name) ?? "null").join(", ");
}

/** Trace-off: the one-liner throw.  Trace-on: bind the boolean so both
 *  outcomes log before the conditional throw (catalog
 *  `precondition_evaluated`). */
function precondition(
  expr: ExprIR,
  source: string,
  message: MessageIR | undefined,
  index: number,
  ctx: JavaRenderContext,
  traceCtx: JavaTraceCtx,
): string {
  // A NAMED precondition in an aggregate operation carries its wire code and
  // pointer THROUGH the throw.
  const code = traceCtx.domainFloorCodes ? domainFloorCode(message) : undefined;
  const text = JSON.stringify(floorRuleText({ expr, source, message }));
  const thrown = code
    ? `throw new DomainException(${text}, DomainException.Kind.PRECONDITION, ${JSON.stringify(code)}, ${JSON.stringify(domainFloorPointer({ expr, source }))}${message ? javaRuleParamsTail({ expr }, (e) => renderJavaExpr(e, ctx)) : ""})`
    : `throw new DomainException(${text}, DomainException.Kind.PRECONDITION)`;
  if (!traceCtx.emitTrace) {
    return `${INDENT}if (!(${renderJavaExpr(expr, ctx)})) ${thrown};`;
  }
  const ok = `__pre_${index}_ok`;
  return [
    `${INDENT}var ${ok} = (${renderJavaExpr(expr, ctx)});`,
    `${INDENT}DomainLog.trace("precondition_evaluated", "${traceCtx.aggregate}", "${traceCtx.op}", ${JSON.stringify(source)}, ${ok});`,
    `${INDENT}if (!${ok}) ${thrown};`,
  ].join("\n");
}

/** Under --trace, append a `value_computed` line after a scalar assign. */
function withValueComputed(base: string, target: PathIR, traceCtx: JavaTraceCtx): string {
  if (!traceCtx.emitTrace) return base;
  if (target.segments.length !== 1) return base;
  const field = target.segments[0]!;
  return [
    base,
    `${INDENT}DomainLog.traceValue("value_computed", "${traceCtx.aggregate}", "${field}", ${renderPath(target)});`,
  ].join("\n");
}

/** Wrap a provenanced write (a statement carrying a `ProvSite`) with lineage
 *  capture — the Java mirror of the Hono `withTrace` / .NET `withProvCapture`.
 *  Snapshot the leaf inputs *before* the mutation (so a self-referential
 *  `x := x + n` records the pre-write value), perform the write, then build the
 *  `ProvLineage` (rule snapshot + inputs + post-write computed value) and route
 *  it to both sinks: the co-located `<field>Provenance` field (current lineage,
 *  persisted on the row) and the per-instance `_provTraces` buffer (drained
 *  into provenance_records by the repository inside the save transaction).
 *
 *  PRESERVED INCONSISTENCY (audit C1): java and .NET gate on `prov` presence
 *  alone (no `emitProvenance` switch) and skip write-throughs into a
 *  containment; node and python honour the switch and capture at any path
 *  depth.  Kept verbatim — reconciling them is a behaviour change on some
 *  backend, not a refactor. */
function withProvCapture(
  base: string,
  prov: ProvSite | undefined,
  target: PathIR,
  value: ExprIR,
  index: number,
  ctx: JavaRenderContext,
  targetType?: TypeIR,
): string {
  if (!prov) return base;
  // Co-located capture is for top-level provenanced fields of the aggregate
  // root (the `<field>Provenance` field + `_provTraces` buffer live on the
  // root).  A write-through into a containment (segments.length > 1) carries no
  // co-located slot — skip, mirroring the value-computed trace's same guard.
  if (target.segments.length !== 1) return base;
  const inputs = collectLeaves(value, (x) => renderJavaExpr(x, ctx))
    .map((l) => `new ProvInput(${JSON.stringify(l.path)}, ${javaLineageValue(l.value, l.type)})`)
    .join(", ");
  const { tmp, lin } = provTempNames(index);
  // A collection target (`add` / `remove`) records the collection as it is.
  const computed = javaLineageValue(renderPath(target), targetType);
  const field = `${prov.target.field}Provenance`;
  const targetLit = `new ProvTarget(${JSON.stringify(prov.target.type)}, ${JSON.stringify(prov.target.field)})`;
  return wrapProvCapture(base, {
    snapshot: `${INDENT}var ${tmp} = java.util.List.<ProvInput>of(${inputs});`,
    lineage: `${INDENT}var ${lin} = new ProvLineage(${JSON.stringify(prov.snapshotId)}, ${targetLit}, ${tmp}, ${computed});`,
    colocated: `${INDENT}this.${field} = ${lin};`,
    sink: `${INDENT}this._provTraces.add(${lin});`,
  });
}

/** Mutation paths read/write fields directly — generated domain classes
 *  keep fields package-private precisely so the aggregate can write
 *  through its containments (`this.profile.bio = …`).  `this.` prefixes
 *  the head so operation params can't shadow the field. */
function renderPath(p: PathIR): string {
  // Each segment is a DECLARED member name, so it carries the same mangling
  // the entity emitter applied to the field it writes (`this.case` →
  // `this.case_`).  `jid` is identity for every non-keyword segment.
  return `this.${p.segments.map(jid).join(".")}`;
}
